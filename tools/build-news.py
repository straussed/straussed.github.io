#!/usr/bin/env python3
"""Regenerate the news gallery in news.html from content/news-items.txt.

    input:  content/news-items.txt   (hand-edited; see the header in that file)
            images/news/             (derivatives from tools/build-images.sh)
    output: news.html                (only between the BEGIN/END markers)

Everything outside the two marker comments in news.html is left byte for byte
alone, so the header, footer and nav stay hand-editable.

Usage: ./tools/build-news.py           # rewrite the gallery
       ./tools/build-news.py --check   # exit 1 if the file is out of date
"""

import html
import re
import subprocess
import sys
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "content" / "news-items.txt"
PAGE = ROOT / "news.html"
NEWS_DIR = ROOT / "images" / "news"

BEGIN = "<!-- BEGIN NEWS: generated by tools/build-news.py — edit content/news-items.txt -->"
END = "<!-- END NEWS -->"

# Must match tools/build-images.sh WIDTHS. The gallery is two columns inside a
# 960px container (920px of content, 1.5rem gap), so a column is 448px; below
# the 700px breakpoint it goes single column and fills the viewport.
WIDTHS = (960, 1920)
SIZES = "(max-width: 700px) calc(100vw - 2.5rem), 448px"

FIELDS = ("image", "date", "caption")

# Markdown links in a caption: [text](url). The text stops at the first ] and
# the url takes no spaces or parens, so a caption can still contain a literal
# bracket or a parenthetical without being mistaken for a link.
LINK = re.compile(r"\[([^\[\]]+)\]\(([^()\s]+)\)")

# Anything else -- javascript:, data: -- would be an XSS vector if a caption
# ever came from somewhere less trusted than this repo.
SAFE_SCHEMES = ("http://", "https://", "mailto:")

# `image` may be repeated to put several photos under one caption; the others
# may not, since two dates or two captions in a block is always a mistake.
REPEATABLE = frozenset({"image"})

# Dates are written as ISO in the manifest so they can be sorted, but displayed
# as month + year. The day is accepted and used for ordering within a month,
# then dropped for display.
DATE_FORMATS = ("%Y-%m-%d", "%Y-%m")


def slugify(name: str) -> str:
    """Mirror of slugify() in tools/build-images.sh."""
    slug = re.sub(r"[^a-z0-9]+", "-", name.lower())
    return slug.strip("-")


def parse_date(value: str, image: str) -> datetime:
    for fmt in DATE_FORMATS:
        try:
            return datetime.strptime(value, fmt)
        except ValueError:
            continue
    die(f"{image}: date {value!r} is not YYYY-MM-DD or YYYY-MM.\n"
        f"       Dates have to be sortable, so free text like 'Summer 2026' "
        f"will not work.")


def parse_manifest(text: str) -> list[dict]:
    """Parse blank-line-separated `key: value` blocks, with indented wrapping."""
    items, block, key = [], {}, None

    def flush(line_no: int) -> None:
        nonlocal block, key
        if block:
            missing = [f for f in FIELDS if f not in block]
            if missing:
                die(f"item ending at line {line_no} is missing: {', '.join(missing)}")
            items.append(block)
        block, key = {}, None

    for line_no, raw in enumerate(text.splitlines(), 1):
        if raw.lstrip().startswith("#"):
            continue
        if not raw.strip():
            flush(line_no)
            continue
        # An indented line continues the previous field rather than starting one.
        if raw[0].isspace() and key:
            if key in REPEATABLE:
                block[key][-1] += " " + raw.strip()
            else:
                block[key] += " " + raw.strip()
            continue
        field, sep, value = raw.partition(":")
        field = field.strip().lower()
        if not sep or field not in FIELDS:
            die(f"line {line_no}: expected one of {FIELDS}, got {raw.strip()!r}")
        key = field
        if field in REPEATABLE:
            block.setdefault(field, []).append(value.strip())
        else:
            if field in block:
                die(f"line {line_no}: duplicate {field!r} in the same item")
            block[field] = value.strip()

    flush(len(text.splitlines()) + 1)
    return items


def unlink_markdown(caption: str) -> str:
    """Markdown links reduced to just their text, for alt attributes.

    A screen reader reading out a URL is noise, and the caption right below the
    photo carries the actual link anyway.
    """
    return LINK.sub(lambda m: m.group(1), caption)


def linkify(caption: str) -> str:
    """Escape a caption for HTML, turning [text](url) into an anchor.

    Escaping is per segment rather than over the whole string: the anchor has to
    reach the page as markup, but the prose around it -- and the link text and
    href themselves -- still needs escaping.
    """
    out, pos = [], 0
    for match in LINK.finditer(caption):
        text, url = match.group(1), match.group(2)
        # A scheme is a colon before the first slash; without one this is a
        # relative link like research.html or #section, which is fine.
        scheme = ":" in url.split("/")[0]
        if scheme and not url.startswith(SAFE_SCHEMES):
            die(f"caption link {url!r}: only http, https, mailto and relative "
                f"links are allowed")
        # Matches the rest of the site: links off to another site open in a new
        # tab. Relative links navigate in place, and a mailto hands off to a
        # mail client, so neither wants a new tab.
        offsite = url.startswith(("http://", "https://"))
        external = ' target="_blank" rel="noopener"' if offsite else ""
        out.append(html.escape(caption[pos:match.start()], quote=False))
        out.append(f'<a href="{html.escape(url, quote=True)}"{external}>'
                   f'{html.escape(text, quote=False)}</a>')
        pos = match.end()
    out.append(html.escape(caption[pos:], quote=False))
    return "".join(out)


def dimensions(path: Path) -> tuple[int, int]:
    out = subprocess.run(
        ["magick", "identify", "-format", "%w %h", str(path)],
        capture_output=True, text=True, check=True,
    ).stdout.split()
    return int(out[0]), int(out[1])


def picture(image: str, caption: str, eager: bool) -> str:
    """One <picture> block. `caption` is "" for all but the first of a group."""
    rel = "images/news"
    slug = slugify(Path(image).stem)
    built = {w: NEWS_DIR / f"{slug}-{w}.jpg" for w in WIDTHS}

    missing = [p.name for p in built.values() if not p.exists()]
    if missing:
        die(f"{image}: {', '.join(missing)} not built.\n"
            f"       Put the original in images/large_image_originals/news/ "
            f"and run ./tools/build-images.sh")

    jpg_srcset = ", ".join(f"{rel}/{slug}-{w}.jpg {w}w" for w in WIDTHS)

    # build-images.sh drops a WebP that lost to its JPEG, so only advertise
    # the widths that actually exist — <picture> always prefers the WebP
    # source, and pointing it at a missing file would 404.
    webp = [w for w in WIDTHS if (NEWS_DIR / f"{slug}-{w}.webp").exists()]
    source = ""
    if webp:
        webp_srcset = ", ".join(f"{rel}/{slug}-{w}.webp {w}w" for w in webp)
        source = (f'\n            <source type="image/webp"\n'
                  f'                    srcset="{webp_srcset}"\n'
                  f'                    sizes="{SIZES}">')

    w, h = dimensions(built[WIDTHS[0]])
    # The first two photos are above the fold on most screens; lazy-loading them
    # would delay the largest contentful paint rather than saving anything.
    loading = "" if eager else ' loading="lazy"'

    return (f'          <picture>{source}\n'
            f'            <img src="{rel}/{slug}-{WIDTHS[0]}.jpg"\n'
            f'                 srcset="{jpg_srcset}"\n'
            f'                 sizes="{SIZES}"\n'
            f'                 width="{w}" height="{h}"{loading} decoding="async"\n'
            f'                 alt="{html.escape(unlink_markdown(caption), quote=True)}">\n'
            f'          </picture>')


def render(items: list[dict]) -> str:
    out, shown = [], 0
    for item in items:
        # The caption doubles as the alt text, so writing an item takes three
        # fields instead of four. The trade is that a screen reader hears the
        # same sentence twice -- once for the image, once for the caption.
        #
        # In a group only the first photo carries it: the caption describes the
        # set as a whole, so repeating it per photo would read as three
        # identical images rather than one story. The rest take alt="", which
        # tells a screen reader to skip them and leans on the caption instead.
        pictures = []
        for n, image in enumerate(item["image"]):
            pictures.append(picture(image, item["caption"] if n == 0 else "",
                                    eager=shown < 2))
            shown += 1

        classes = "news-photo news-photo--group" if len(pictures) > 1 else "news-photo"
        out.append(
            f'        <figure class="{classes}">\n'
            + "\n".join(pictures) + "\n"
            f'          <figcaption>\n'
            f'            <span class="news-caption-date">{item["_date"].strftime("%B %Y")}</span>\n'
            f'            &mdash; {linkify(item["caption"])}\n'
            f'          </figcaption>\n'
            f'        </figure>'
        )
    return "\n\n".join(out)


def die(message: str) -> None:
    sys.exit(f"error: {message}")


def main() -> None:
    check_only = "--check" in sys.argv[1:]

    if not MANIFEST.exists():
        die(f"{MANIFEST.relative_to(ROOT)} not found")

    items = parse_manifest(MANIFEST.read_text())
    if not items:
        # Refuse rather than silently publishing an empty page: an empty
        # manifest is almost always a typo, not a request to delete the news.
        die("no items in the manifest — refusing to write an empty gallery")

    # Newest first, so the manifest can be kept in whatever order is convenient
    # to edit. Ties (two items in the same month, or the same day) keep their
    # manifest order, since Python's sort is stable.
    for item in items:
        item["_date"] = parse_date(item["date"], item["image"])
    items.sort(key=lambda item: item["_date"], reverse=True)

    page = PAGE.read_text()
    if BEGIN not in page or END not in page:
        die(f"markers not found in {PAGE.name}; expected\n  {BEGIN}\n  {END}")

    head, _, rest = page.partition(BEGIN)
    _, _, tail = rest.partition(END)
    updated = f"{head}{BEGIN}\n\n{render(items)}\n\n{' ' * 8}{END}{tail}"

    if updated == page:
        print(f"news.html already up to date ({len(items)} items)")
        return
    if check_only:
        sys.exit("error: news.html is out of date — run ./tools/build-news.py")

    PAGE.write_text(updated)
    print(f"wrote {len(items)} items into news.html")


if __name__ == "__main__":
    main()
